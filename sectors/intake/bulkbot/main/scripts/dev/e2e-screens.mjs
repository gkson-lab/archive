// Scans the fake-camera clip for a while, then screenshots every screen and sheet (visual QA).
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const [clip, outDir] = process.argv.slice(2);
const proxy = process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: 'localhost,127.0.0.1' } : undefined;
const browser = await chromium.launch({ proxy, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', `--use-file-for-fake-video-capture=${clip}`, '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, permissions: ['camera'], hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://localhost:4173/#scan');
await page.waitForFunction(() => !document.querySelector('.status-pill')?.textContent?.match(/Downloading|Loading/), null, { timeout: 180000 });
await page.waitForFunction(() => (document.querySelector('.tray .total span')?.textContent ?? '').match(/^[3-9]\d* cards|^\d{2,} cards/), null, { timeout: 90000 });
await page.screenshot({ path: `${outDir}/s1-scan.png` });
await page.click('.tray .mini');
await page.waitForTimeout(1200);
await page.screenshot({ path: `${outDir}/s2-detail.png` });
await page.keyboard.press('Escape');
await page.click('.tabbar button:nth-child(2)');
await page.waitForTimeout(600);
await page.screenshot({ path: `${outDir}/s3-session.png` });
await page.click('.tabbar button:nth-child(3)');
await page.waitForTimeout(600);
await page.screenshot({ path: `${outDir}/s4-collection.png` });
await page.click('.tabbar button:nth-child(4)');
await page.fill('.search-box input', 'charizard');
await page.waitForTimeout(700);
await page.screenshot({ path: `${outDir}/s5-search.png` });
await page.click('.tabbar button:nth-child(5)');
await page.waitForTimeout(600);
await page.screenshot({ path: `${outDir}/s6-settings.png` });
console.log('page errors:', errors);
await browser.close();
